// Browser test for the booking sheet: pick the departure date (nights follow), then book several rooms at once as one group booking.
import { chromium } from 'playwright';
import { BASE, session } from './lib.mjs';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const fail = []; const check = (name, cond) => { console.log((cond ? 'PASS ' : 'FAIL ') + name); if (!cond) fail.push(name); };
const ctx = await browser.newContext({ viewport: { width: 1366, height: 900 } });
const page = await ctx.newPage(); page.on('pageerror', (e) => { console.log('PAGEERROR', e.message); fail.push(`pageerror ${e.message}`); });
await page.goto(BASE);
await page.getByLabel(/Company code/).fill('sunset'); await page.getByLabel(/Email/).fill('hira@sunset.local'); await page.getByLabel(/Password/).fill(process.env.E2E_PASSWORD ?? 'sunset-demo-passphrase'); await page.getByRole('button', { name: /sign in/i }).click();
await page.getByRole('navigation', { name: /Main navigation/ }).first().waitFor();
await page.evaluate(() => { window.location.hash = '/reservations?tab=bookings&new=1'; });
const sheet = page.getByRole('dialog', { name: 'New booking' }); await sheet.waitFor();
const arrival = await sheet.getByLabel('Arrival').inputValue();
const plus = (n) => new Date(Date.parse(`${arrival}T00:00:00Z`) + n * 86_400_000).toISOString().slice(0, 10);
await sheet.getByLabel('Departure').fill(plus(3));
check('picking the departure date sets the nights', (await sheet.getByLabel('Nights').inputValue()) === '3');
await sheet.getByLabel('Nights').fill('2');
check('changing the nights moves the departure date', (await sheet.getByLabel('Departure').inputValue()) === plus(2));
await sheet.getByRole('button', { name: 'Check availability' }).click();
const more = sheet.getByRole('button', { name: 'One room more' });
await more.first().waitFor(); await more.first().click(); await more.first().click(); await more.nth(1).click();
check('a group is picked: 3 rooms', /Continue with 3 room/.test(await sheet.innerText()));
await sheet.getByRole('button', { name: /Continue with 3 room/ }).click();
await sheet.getByLabel('Full name').fill('Group Leader'); await sheet.getByLabel('Phone').fill(`0300 ${String(Date.now()).slice(-7)}`);
await sheet.getByRole('button', { name: /Continue with this guest/ }).first().click();
await sheet.getByRole('button', { name: /Confirm booking/ }).click();
await sheet.getByText(/BLVD-/).first().waitFor(); check('the group becomes one booking', true);
const s = await session('hira@sunset.local'); const pid = (await s.get('/v1/me/properties')).items.find((p) => p.name.endsWith('Boulevard')).id;
const list = (await s.get(`/v1/properties/${pid}/reservations?limit=5`)).items; const res = await s.get(`/v1/properties/${pid}/reservations/${list[0].reservationId}`);
check('with three rooms in it', res.lines.length === 3);
await browser.close(); if (fail.length) { console.log('FAILED', fail); process.exit(1); } console.log('all passed');

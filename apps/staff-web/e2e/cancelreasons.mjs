// Browser test: cancelling asks for a standard reason and who started it; the cancellations report shows and groups by them.
import { chromium } from 'playwright';
import { session, book, addDays, BASE } from './lib.mjs';
const fail = []; const check = (name, cond) => { console.log((cond ? 'PASS ' : 'FAIL ') + name); if (!cond) fail.push(name); };
const hira = await session('hira@sunset.local');
const pid = (await hira.get('/v1/me/properties')).items.find((p) => p.name.endsWith('Boulevard')).id; const P = `/v1/properties/${pid}`;
const bd = (await hira.get(P)).businessDate;
const b = await book(hira, pid, { name: 'Cancelling Guest', phone: `0300${String(Date.now()).slice(-7)}`, arrival: addDays(bd, 20), nights: 2 });
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await (await browser.newContext({ viewport: { width: 1366, height: 900 } })).newPage(); page.on('pageerror', (e) => { console.log('PAGEERROR', e.message); fail.push(`pageerror ${e.message}`); });
await page.goto(BASE);
await page.getByLabel(/Company code/).fill('sunset'); await page.getByLabel(/Email/).fill('hira@sunset.local'); await page.getByLabel(/Password/).fill(process.env.E2E_PASSWORD ?? 'sunset-demo-passphrase'); await page.getByRole('button', { name: /sign in/i }).click();
await page.getByRole('navigation', { name: /Main navigation/ }).first().waitFor();
await page.goto(`${BASE}/#/reservations/${b.id}`);
await page.getByRole('button', { name: /^Cancel booking$/ }).first().click();
const sheet = page.getByRole('dialog'); await sheet.waitFor();
check('confirming is not possible until a reason is chosen', await sheet.getByRole('button', { name: 'Confirm' }).isDisabled());
await sheet.getByLabel('Why was it lost').selectOption('FOUND_ELSEWHERE');
check('who started it follows the reason: the guest', (await sheet.getByLabel('Who started it').inputValue()) === 'GUEST');
await sheet.getByLabel('Why was it lost').selectOption('OVERBOOKED');
check('and changes with it: the property', (await sheet.getByLabel('Who started it').inputValue()) === 'PROPERTY');
await sheet.getByLabel('Note').fill('Two rooms were out of order');
await sheet.getByRole('button', { name: 'Confirm' }).click();
await page.getByText('Cancelled', { exact: true }).first().waitFor({ timeout: 15000 }); check('the booking is cancelled', true);
const line = (await hira.get(`${P}/reservations/${b.id}`)).lines[0];
const rep = await hira.get(`${P}/insights/cancellations?from=${bd}&to=${addDays(bd, 1)}&group=reason`);
check('the report groups by the reason', rep.rows.some((r) => r.what === 'We could not honour it (overbooked)' && r.n >= 1));
const list = await hira.get(`${P}/insights/cancellations?from=${bd}&to=${addDays(bd, 1)}`);
check('and lists who started it', list.rows.some((r) => r.reason === 'We could not honour it (overbooked)' && r.initiator === 'Property' && r.why === 'Two rooms were out of order'));
await browser.close(); if (fail.length) { console.log('FAILED', fail); process.exit(1); } console.log('all passed');

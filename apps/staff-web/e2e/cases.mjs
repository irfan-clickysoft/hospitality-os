// Browser test for the damage and complaint registers: report damage with a picture, confirm it, tell the guest; log a restricted case that the front desk cannot see; accessibility of both pages.
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { BASE } from './lib.mjs';
const AXE = readFileSync(createRequire(import.meta.url).resolve('axe-core/axe.min.js'), 'utf8');
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const fail = []; const check = (name, cond) => { console.log((cond ? 'PASS ' : 'FAIL ') + name); if (!cond) fail.push(name); };
const ctx = await browser.newContext({ viewport: { width: 1366, height: 900 } });
const page = await ctx.newPage(); page.on('pageerror', (e) => { console.log('PAGEERROR', e.message); fail.push(`pageerror ${e.message}`); });
await page.goto(BASE);
await page.getByLabel(/Company code/).fill('sunset'); await page.getByLabel(/Email/).fill('hira@sunset.local'); await page.getByLabel(/Password/).fill(process.env.E2E_PASSWORD ?? 'sunset-demo-passphrase'); await page.getByRole('button', { name: /sign in/i }).click();
await page.getByRole('navigation', { name: /Main navigation/ }).first().waitFor();
await page.evaluate(() => { window.location.hash = '/tasks?tab=damage'; });
await page.getByRole('heading', { name: 'Damage register' }).waitFor();
await page.getByRole('button', { name: 'Report damage' }).first().click();
const sheet = page.getByRole('dialog', { name: 'Report damage' }); await sheet.waitFor();
await sheet.getByLabel('Room').selectOption({ index: 1 });
await sheet.getByLabel('Item or area').fill('Bathroom mirror'); await sheet.getByLabel('What happened').fill('Mirror cracked across the corner, found at turnover');
await sheet.getByLabel(/Estimated cost/).fill('4500');
await sheet.getByRole('button', { name: 'Report', exact: true }).click();
const detail = page.getByRole('dialog', { name: /DMG-.*Bathroom mirror/ }); await detail.waitFor();
check('a new report starts as suspected', (await detail.getByText('Suspected').count()) > 0);
await detail.locator('input[type=file]').setInputFiles('/tmp/work/evidence.png');
await detail.locator('img.photo-thumb').first().waitFor(); check('the picture is attached as evidence', true);
check('charging is not offered for suspected damage', (await detail.getByRole('button', { name: /Approve charge|Charge to the bill/ }).count()) === 0);
await detail.getByRole('button', { name: 'Confirm damage' }).click(); await detail.getByRole('group', { name: 'Confirm damage' }).getByRole('button', { name: 'Confirm damage' }).click();
await detail.getByText('Confirmed').first().waitFor(); check('the case is confirmed', true);
await detail.getByRole('button', { name: 'Guest has been told' }).click(); await detail.getByText('Guest told').first().waitFor();
check('the history shows each step', (await detail.getByText('Reported').count()) > 0 && (await detail.getByText('Confirmed').count()) > 0);
await page.screenshot({ path: '/tmp/work/dmg.png' });
await detail.getByRole('button', { name: 'Close' }).first().click().catch(() => undefined);
await page.evaluate(() => { window.location.hash = '/tasks?tab=cases'; });
await page.getByRole('heading', { name: 'Complaints and incidents' }).waitFor();
await page.getByRole('button', { name: 'Log a case' }).first().click();
const cs = page.getByRole('dialog', { name: 'Log a case' }); await cs.waitFor();
await cs.getByLabel('Type').selectOption('SECURITY'); await cs.getByLabel('What happened').fill('Side door found unlocked at 2 am');
await cs.getByRole('button', { name: 'Log it' }).click();
await page.getByText('Restricted cases are not shown to you.').waitFor();
check('a security case the front desk logged is not visible to the front desk', (await page.getByText('Side door found unlocked').count()) === 0);
await page.getByRole('button', { name: 'Log a case' }).first().click();
const c2 = page.getByRole('dialog', { name: 'Log a case' }); await c2.waitFor();
await c2.getByLabel('Type').selectOption('GUEST_COMPLAINT'); await c2.getByLabel('What happened').fill('Air conditioner too noisy at night');
await c2.getByRole('button', { name: 'Log it' }).click();
const cd = page.getByRole('dialog', { name: /CASE-.*Guest complaint/ }); await cd.waitFor();
check('an ordinary complaint opens with its target time', (await cd.getByText('Target time to resolve').count()) > 0);
await cd.getByRole('button', { name: 'Close' }).first().click().catch(() => undefined);
for (const [name, hash] of [['damage', '/tasks?tab=damage'], ['cases', '/tasks?tab=cases']]) {
  await page.evaluate((h) => { window.location.hash = h; }, hash); await page.waitForTimeout(900);
  await page.addScriptTag({ content: AXE });
  const r = await page.evaluate(async () => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'] } }));
  const bad = r.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical');
  check(`accessibility: ${name} has no serious findings${bad.length ? ' — ' + bad.map((v) => v.id).join(',') : ''}`, bad.length === 0);
}
await browser.close(); if (fail.length) { console.log('FAILED', fail); process.exit(1); } console.log('all passed');

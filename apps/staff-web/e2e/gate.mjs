// Browser test for gate security on a phone, in Urdu (needs the API, the dev seed and the dev server running — run after scripts/reset-dev.sh).
import { chromium } from 'playwright';
const BASE = process.env.STAFF_URL ?? 'http://localhost:3001';
const OUT = process.argv[2] ?? '.';
const browser = await chromium.launch({ ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] });
const fail = [];
const check = (name, cond) => { console.log((cond ? 'PASS ' : 'FAIL ') + name); if (!cond) fail.push(name); };
const ctx = await browser.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => { console.log('PAGEERROR', e.message); fail.push('pageerror ' + e.message); });
await page.goto(BASE);
await page.getByLabel(/Company code|کمپنی کوڈ/).fill('sunset');
await page.getByLabel(/Email|ای میل/).fill('gate@sunset.local');
await page.getByLabel(/Password|پاس ورڈ/).fill(process.env.E2E_PASSWORD ?? 'sunset-demo-passphrase');
await page.locator('form button.primary').click();
await page.locator('nav.tabs').waitFor();
check('the gate screen opens in Urdu', (await page.evaluate(() => document.documentElement.dir)) === 'rtl' && await page.getByRole('heading', { name: 'گیٹ' }).count() === 1);
check('the gate user has no money or guest-data tabs', await page.locator('nav.tabs button', { hasText: /Cashier|Reports|Rack|Bookings|کیشیئر/ }).count() === 0);
await page.getByRole('button', { name: 'اندراج کریں' }).click();
await page.getByLabel('نام', { exact: true }).fill('Imran Shah');
await page.getByLabel('گاڑی نمبر').fill('bkx-123');
await page.getByLabel('ملاقات کے لیے').fill('Room 101');
await page.screenshot({ path: `${OUT}/30-gate-log.png` });
await page.getByRole('button', { name: 'اندر درج کریں' }).click();
await page.getByText('Imran Shah · BKX-123').first().waitFor();
check('visitor is logged with the vehicle number in capitals', true);
await page.screenshot({ path: `${OUT}/31-gate.png` });
await page.getByRole('button', { name: 'باہر چلا گیا' }).first().click();
await page.getByRole('button', { name: 'باہر چلا گیا' }).waitFor({ state: 'detached' });
check('visitor is marked gone and moves to today’s list', await page.getByText('Imran Shah · BKX-123').count() === 1);
await page.screenshot({ path: `${OUT}/32-gate-after.png` });
await browser.close();
console.log(fail.length ? `\n${fail.length} FAILED` : '\nALL PASSED');
process.exit(fail.length ? 1 : 0);
